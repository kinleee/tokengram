# Header-sniff yalnız bu uzantılara tətbiq olunur — qalan fayllar üçün
# açılış/oxuma xərci çəkilmir.
_C_LIKE_SUFFIXES = {".c", ".cpp", ".cc", ".cxx", ".h", ".hpp"}


def is_cython_generated(file_path) -> bool:
    """Cython-un generasiya etdiyi .c/.cpp faylını başlıq imzasından tanı.

    Bu fayllar mənbə kod deyil: bir .py faylından 20-50K sətir C çıxır.
    Dev maşınında indeksin 7659 chunk-ından 6364-ü bunlar idi — axtarış
    keyfiyyətini boğur, reindex-i 10 dəqiqədən 40-a çıxarırdı. İmza
    ("Generated by Cython") faylın ilk sətirlərində standartdır.
    """
    p = Path(file_path)
    if p.suffix not in _C_LIKE_SUFFIXES:
        return False
    try:
        with open(p, "r", encoding="utf-8", errors="replace") as fh:
            head = fh.read(300)
    except OSError:
        return False
    return "Generated by Cython" in head


def find_code_files(directory: str) -> List[Path]:
    """Verilmiş qovluqda dəstəklənən kod fayllarını rekursiv olaraq tapır.
    
    Args:
        directory: Axtarılacaq qovluğun yolu
        
    Returns:
        Tapılan faylların Path siyahısı
        
    Raises:
        FileNotFoundError: Qovluq mövcud deyilsə
        PermissionError: Qovluğa giriş icazəsi yoxdursa
    """
    dir_path = Path(directory).resolve()
    
    if not dir_path.exists():
        raise FileNotFoundError(f"Qovluq tapılmadı: {dir_path}")
    
    if not dir_path.is_dir():
        raise NotADirectoryError(f"Bu bir qovluq deyil: {dir_path}")
    
    found_files = []

    # `os.walk` + `dirs[:]` prune — istisna qovluqlara (vendor, node_modules...)
    # HEÇ girmirik. Köhnə `rglob("*")` hər qovluğa enib sonra faylı atırdı:
    # 12542 faylı stat etmək saniyələrlə çəkirdi. Prune ilə walk yüzlərlə fayla
    # enir, vendor/ ümumiyyətlə açılmır.
    import os as _os
    try:
        for root, dirs, filenames in _os.walk(dir_path):
            # Yerində prune — walk bu alt-ağaclara enməyəcək
            dirs[:] = [d for d in dirs if d not in config.EXCLUDED_DIRS]

            for fname in filenames:
                file_path = Path(root) / fname

                # Fayl uzantısı yoxlaması
                if file_path.suffix not in config.SUPPORTED_EXTENSIONS:
                    continue

                # Fayl adı / suffix qara siyahısı (lock faylları, minified
                # bundles, generated kod, MLA internal state)
                if any(fname.startswith(p) for p in config.EXCLUDED_FILE_PATTERNS):
                    continue
                if any(fname.endswith(s) for s in config.EXCLUDED_FILE_SUFFIXES):
                    continue

                # Ölçü tavanı — vendor bundle / data dump faylları embedding-də
                # OOM və ya indeksdə şişməyə səbəb ola bilər
                try:
                    if file_path.stat().st_size > config.MAX_FILE_SIZE_BYTES:
                        logger.debug(f"Ölçü tavanı keçildi, keçildi: {file_path}")
                        continue
                except OSError:
                    continue

                # Cython-generated C — mənbə deyil, minlərlə junk chunk mənbəyi
                if is_cython_generated(file_path):
                    continue

                found_files.append(file_path)

    except PermissionError as e:
        logger.warning(f"İcazə xətası, bəzi fayllar keçildi: {e}")

    # Layihənin öz `.gitignore`-una hörmət — sabit EXCLUDED_* siyahısının tutmadığı
    # layihəyə-xas ignore-ları da kənarlaşdır (tracked fayllar qorunur, qeyri-git
    # qovluqda no-op). Tək batch git-subprocess, ona görə walk-dan SONRA tətbiq olunur.
    before = len(found_files)
    found_files = config.filter_gitignored(dir_path, found_files)
    skipped = before - len(found_files)
    if skipped:
        logger.info(f"🚫 {skipped} fayl .gitignore qaydaları ilə kənarlaşdırıldı")

    logger.info(f"📁 {len(found_files)} kod faylı tapıldı: {dir_path}")
    return sorted(found_files)


